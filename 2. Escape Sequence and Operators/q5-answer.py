'''
Take a number as a input. Print the result of that number raised to the 
power of 3 using **. Also print what //7 and %7 give for the same number
'''

number = int(input("Enter Your Number = "))

update_number = number**3

print(f"Power is = {update_number}, floor division is = {update_number//7} and mod number is = {update_number%7}")
